--
-- A schema other than the session's, like the one owning a package called through a synonym.
-- The names do not exist in PLSQL_TEST, so that a name without an owner cannot find the wrong type by luck.
--

CREATE TABLE OWNER_ITEM
(
	ID           NUMBER(10) NOT NULL,
	DESCRIPTION  VARCHAR2(60 CHAR)
);

CREATE TYPE OWNER_ADDRESS_T AS OBJECT
(
	STREET  VARCHAR2(60),
	NUM     NUMBER(6)
);
/

CREATE TYPE OWNER_ADDRESS_LIST_T AS TABLE OF OWNER_ADDRESS_T;
/

CREATE TYPE OWNER_NAME_LIST_T AS TABLE OF VARCHAR2(60);
/

CREATE TYPE OWNER_WITH_ADDRESS_T AS OBJECT
(
	ID       NUMBER(10),
	ADDRESS  OWNER_ADDRESS_T,
	NAMES    OWNER_NAME_LIST_T
);
/

CREATE OR REPLACE PACKAGE FIXTURE_OF_OWNER AS

	TYPE owner_entry IS RECORD (ID NUMBER(10), DESCRIPTION VARCHAR2(60));
	TYPE owner_entry_list IS TABLE OF owner_entry;

	FUNCTION constant RETURN NUMBER;
	FUNCTION echo_address(p_value OWNER_ADDRESS_T) RETURN OWNER_ADDRESS_T;
	FUNCTION echo_addresses(p_value OWNER_ADDRESS_LIST_T) RETURN OWNER_ADDRESS_LIST_T;
	FUNCTION echo_names(p_value OWNER_NAME_LIST_T) RETURN OWNER_NAME_LIST_T;
	FUNCTION echo_nested(p_value OWNER_WITH_ADDRESS_T) RETURN OWNER_WITH_ADDRESS_T;
	FUNCTION echo_entry(p_value owner_entry) RETURN owner_entry;
	FUNCTION echo_entries(p_value owner_entry_list) RETURN owner_entry_list;
	FUNCTION echo_rowtype(p_value OWNER_ITEM%ROWTYPE) RETURN OWNER_ITEM%ROWTYPE;

END FIXTURE_OF_OWNER;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_OF_OWNER AS

	FUNCTION constant RETURN NUMBER IS BEGIN RETURN 42; END;
	FUNCTION echo_address(p_value OWNER_ADDRESS_T) RETURN OWNER_ADDRESS_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_addresses(p_value OWNER_ADDRESS_LIST_T) RETURN OWNER_ADDRESS_LIST_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_names(p_value OWNER_NAME_LIST_T) RETURN OWNER_NAME_LIST_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_nested(p_value OWNER_WITH_ADDRESS_T) RETURN OWNER_WITH_ADDRESS_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_entry(p_value owner_entry) RETURN owner_entry IS BEGIN RETURN p_value; END;
	FUNCTION echo_entries(p_value owner_entry_list) RETURN owner_entry_list IS BEGIN RETURN p_value; END;
	FUNCTION echo_rowtype(p_value OWNER_ITEM%ROWTYPE) RETURN OWNER_ITEM%ROWTYPE IS BEGIN RETURN p_value; END;

END FIXTURE_OF_OWNER;
/

GRANT EXECUTE ON FIXTURE_OF_OWNER TO plsql_test;
GRANT EXECUTE ON OWNER_ADDRESS_T TO plsql_test;
GRANT EXECUTE ON OWNER_ADDRESS_LIST_T TO plsql_test;
GRANT EXECUTE ON OWNER_NAME_LIST_T TO plsql_test;
GRANT EXECUTE ON OWNER_WITH_ADDRESS_T TO plsql_test;
GRANT SELECT ON OWNER_ITEM TO plsql_test;
