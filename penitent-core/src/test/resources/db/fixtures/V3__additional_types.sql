CREATE OR REPLACE PACKAGE FIXTURE_CURSOR_LOB AS
	FUNCTION columns_without_text RETURN SYS_REFCURSOR;
	FUNCTION not_a_number RETURN BINARY_DOUBLE;
END FIXTURE_CURSOR_LOB;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_CURSOR_LOB AS

	FUNCTION columns_without_text RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR
			SELECT TO_CLOB('abc') TEXT, TO_BLOB(HEXTORAW('01')) BYTES, ADDRESS_T('Street A', 1) ADDRESS FROM DUAL;
		RETURN l_cursor;
	END;

	FUNCTION not_a_number RETURN BINARY_DOUBLE IS BEGIN RETURN BINARY_DOUBLE_NAN; END;

END FIXTURE_CURSOR_LOB;
