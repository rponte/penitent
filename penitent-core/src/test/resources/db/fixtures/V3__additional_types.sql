CREATE OR REPLACE PACKAGE FIXTURE_SHAPES AS

	TYPE assoc_by_integer IS TABLE OF VARCHAR2(10) INDEX BY PLS_INTEGER;
	TYPE assoc_by_text IS TABLE OF VARCHAR2(10) INDEX BY VARCHAR2(10);
	TYPE strong_cursor IS REF CURSOR RETURN FIXTURE_ITEM%ROWTYPE;

	FUNCTION echo_assoc_by_integer(p_value assoc_by_integer) RETURN assoc_by_integer;
	FUNCTION echo_assoc_by_text(p_value assoc_by_text) RETURN assoc_by_text;
	FUNCTION echo_matrix(p_value MATRIX_T) RETURN MATRIX_T;
	FUNCTION echo_base(p_value BASE_T) RETURN BASE_T;
	FUNCTION echo_child(p_value CHILD_T) RETURN CHILD_T;
	FUNCTION child_as_base RETURN BASE_T;
	FUNCTION open_strong_cursor RETURN strong_cursor;
	FUNCTION cursor_with_object RETURN SYS_REFCURSOR;
	FUNCTION scalar_cursor RETURN SYS_REFCURSOR;

	PROCEDURE cursor_as_out(p_cursor OUT SYS_REFCURSOR);

END FIXTURE_SHAPES;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_SHAPES AS

	FUNCTION echo_assoc_by_integer(p_value assoc_by_integer) RETURN assoc_by_integer IS BEGIN RETURN p_value; END;
	FUNCTION echo_assoc_by_text(p_value assoc_by_text) RETURN assoc_by_text IS BEGIN RETURN p_value; END;
	FUNCTION echo_matrix(p_value MATRIX_T) RETURN MATRIX_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_base(p_value BASE_T) RETURN BASE_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_child(p_value CHILD_T) RETURN CHILD_T IS BEGIN RETURN p_value; END;
	FUNCTION child_as_base RETURN BASE_T IS BEGIN RETURN CHILD_T(1, 'child'); END;

	FUNCTION open_strong_cursor RETURN strong_cursor IS
		l_cursor strong_cursor;
	BEGIN
		OPEN l_cursor FOR SELECT 1 ID, 'strong' DESCRIPTION, 2.5 QUANTITY, DATE '2018-01-15' REGISTERED_AT FROM DUAL;
		RETURN l_cursor;
	END;

	FUNCTION cursor_with_object RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR SELECT 1 ID, ADDRESS_T('Street A', 1) ADDRESS FROM DUAL;
		RETURN l_cursor;
	END;

	FUNCTION scalar_cursor RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR SELECT 'a' NAME FROM DUAL;
		RETURN l_cursor;
	END;

	PROCEDURE cursor_as_out(p_cursor OUT SYS_REFCURSOR) IS
	BEGIN
		OPEN p_cursor FOR SELECT 1 FROM DUAL;
	END;

END FIXTURE_SHAPES;
