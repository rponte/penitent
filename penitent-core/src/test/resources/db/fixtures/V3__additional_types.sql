-- the body does not compile on purpose, and Oracle signals this as an error in the EXECUTE IMMEDIATE
DECLARE
	e_compiled_with_error EXCEPTION;
	PRAGMA EXCEPTION_INIT(e_compiled_with_error, -24344);
BEGIN
	EXECUTE IMMEDIATE 'CREATE PACKAGE FIXTURE_INVALID AS FUNCTION constant RETURN NUMBER; END;';
	EXECUTE IMMEDIATE 'CREATE PACKAGE BODY FIXTURE_INVALID AS FUNCTION constant RETURN NUMBER IS BEGIN RETURN does_not_exist; END; END;';
EXCEPTION
	WHEN e_compiled_with_error THEN NULL;
END;
