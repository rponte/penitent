CREATE OR REPLACE PACKAGE FIXTURE_ERRORS AS
	PROCEDURE trigger_error(p_error VARCHAR2);
	FUNCTION cursor_with_error RETURN SYS_REFCURSOR;
END FIXTURE_ERRORS;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_ERRORS AS

	PROCEDURE trigger_error(p_error VARCHAR2) IS
		TYPE NAMES IS TABLE OF VARCHAR2(10);
		l_number NUMBER;
		l_zero NUMBER := 0;
		l_date DATE;
		l_text VARCHAR2(1);
		l_long VARCHAR2(10) := 'long';
		l_list NAMES := NAMES('a');
		l_list_null NAMES;
		l_address ADDRESS_T;
		e_own EXCEPTION;
		e_initialized EXCEPTION;
		PRAGMA EXCEPTION_INIT(e_initialized, -20200);
	BEGIN
		-- no WHEN for CASE_NOT_FOUND: that is exactly the error
		CASE p_error
			WHEN 'RAE' THEN RAISE_APPLICATION_ERROR(-20200, 'rule violated');
			WHEN 'RAE_OUT_OF_RANGE' THEN RAISE_APPLICATION_ERROR(-100, 'out of range');
			WHEN 'NO_DATA_FOUND' THEN SELECT 1 INTO l_number FROM DUAL WHERE 1 = 0;
			WHEN 'TOO_MANY_ROWS' THEN SELECT 1 INTO l_number FROM DUAL CONNECT BY LEVEL <= 2;
			WHEN 'ZERO_DIVIDE' THEN l_number := 1 / l_zero;
			WHEN 'VALUE_ERROR' THEN l_text := l_long;
			WHEN 'INVALID_NUMBER' THEN SELECT TO_NUMBER(l_long) INTO l_number FROM DUAL;
			WHEN 'INVALID_DATE' THEN SELECT TO_DATE('0000', 'YYYY') INTO l_date FROM DUAL;
			WHEN 'OWN_EXCEPTION' THEN RAISE e_own;
			WHEN 'EXCEPTION_INIT' THEN RAISE e_initialized;
			WHEN 'SUBSCRIPT' THEN l_text := l_list(2);
			WHEN 'NULL_COLLECTION' THEN l_text := l_list_null(1);
			WHEN 'NULL_OBJECT' THEN l_address.STREET := 'x';
			WHEN 'DUPLICATE_KEY' THEN INSERT INTO FIXTURE_ERROR_ROW (ID, NAME) VALUES (1, 'x');
			WHEN 'NOT_NULL' THEN INSERT INTO FIXTURE_ERROR_ROW (ID, NAME) VALUES (3, NULL);
			WHEN 'CHECK' THEN INSERT INTO FIXTURE_ERROR_ROW (ID, NAME, QTY) VALUES (3, 'x', -1);
			WHEN 'FK_WITHOUT_PARENT' THEN INSERT INTO FIXTURE_ERROR_ROW (ID, NAME, PARENT) VALUES (3, 'x', 99);
			WHEN 'FK_WITH_CHILD' THEN DELETE FROM FIXTURE_ERROR_ROW WHERE ID = 1;
			WHEN 'VALUE_TOO_LARGE' THEN INSERT INTO FIXTURE_ERROR_ROW (ID, NAME) VALUES (3, 'large');
			WHEN 'DYNAMIC_TABLE' THEN EXECUTE IMMEDIATE 'SELECT 1 FROM TABLE_THAT_DOES_NOT_EXIST';
			WHEN 'DYNAMIC_SYNTAX' THEN EXECUTE IMMEDIATE 'THIS IS NOT SQL';
			WHEN 'DYNAMIC_PLSQL' THEN EXECUTE IMMEDIATE 'BEGIN DOES_NOT_EXIST; END;';
			WHEN 'NOWAIT' THEN LOCK TABLE FIXTURE_ERROR_ROW IN EXCLUSIVE MODE NOWAIT;
		END CASE;
	END;

	FUNCTION cursor_with_error RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR SELECT 1 / (ROWNUM - 1) AS VALUE FROM DUAL;
		RETURN l_cursor;
	END;

END FIXTURE_ERRORS;
/
