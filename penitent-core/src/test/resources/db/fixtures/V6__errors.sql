	ID NUMBER PRIMARY KEY,
	NAME VARCHAR2(3) NOT NULL,
	QTY NUMBER CHECK (QTY > 0),
	PARENT NUMBER REFERENCES FIXTURE_ERROR_ROW (ID)
);

