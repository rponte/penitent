--
-- %ROWTYPE records of tables whose columns are not all plain and visible: a virtual and an invisible column, which
-- PL/SQL leaves out of a %ROWTYPE; and an object type, a nested table and a VARRAY as columns.
--

CREATE TABLE FIXTURE_PARCEL
(
	ID            NUMBER PRIMARY KEY,
	WEIGHT        NUMBER,
	DOUBLE_WEIGHT NUMBER GENERATED ALWAYS AS (WEIGHT * 2) VIRTUAL,
	SECRET        VARCHAR2(5) INVISIBLE
);

-- the invisible column filled in one row: only a statement that names it sees it
INSERT INTO FIXTURE_PARCEL (ID, WEIGHT) VALUES (1, 10);
INSERT INTO FIXTURE_PARCEL (ID, WEIGHT, SECRET) VALUES (2, 20, 'shh');

CREATE TABLE FIXTURE_BUNDLE
(
	ID      NUMBER PRIMARY KEY,
	ADDRESS ADDRESS_T,
	NAMES   NAME_LIST_T,
	CODES   NUMBER_VARRAY_T
)
NESTED TABLE NAMES STORE AS FIXTURE_BUNDLE_NAMES;

CREATE PACKAGE FIXTURE_ROWTYPE_COLUMNS AS
	TYPE BUNDLE_LIST IS TABLE OF FIXTURE_BUNDLE%ROWTYPE;

	FUNCTION echo_parcel(p_value FIXTURE_PARCEL%ROWTYPE) RETURN FIXTURE_PARCEL%ROWTYPE;

	FUNCTION echo_bundle(p_value FIXTURE_BUNDLE%ROWTYPE) RETURN FIXTURE_BUNDLE%ROWTYPE;

	FUNCTION echo_bundles(p_value BUNDLE_LIST) RETURN BUNDLE_LIST;

	FUNCTION describe_bundle(p_value FIXTURE_BUNDLE%ROWTYPE) RETURN VARCHAR2;
END FIXTURE_ROWTYPE_COLUMNS;
/

CREATE PACKAGE BODY FIXTURE_ROWTYPE_COLUMNS AS
	FUNCTION echo_parcel(p_value FIXTURE_PARCEL%ROWTYPE) RETURN FIXTURE_PARCEL%ROWTYPE IS
	BEGIN
		RETURN p_value;
	END;

	FUNCTION echo_bundle(p_value FIXTURE_BUNDLE%ROWTYPE) RETURN FIXTURE_BUNDLE%ROWTYPE IS
	BEGIN
		RETURN p_value;
	END;

	FUNCTION echo_bundles(p_value BUNDLE_LIST) RETURN BUNDLE_LIST IS
	BEGIN
		RETURN p_value;
	END;

	FUNCTION describe_bundle(p_value FIXTURE_BUNDLE%ROWTYPE) RETURN VARCHAR2 IS
	BEGIN
		RETURN p_value.address.street || '/' || p_value.names.COUNT || '/' || p_value.codes.COUNT;
	END;
END FIXTURE_ROWTYPE_COLUMNS;
/
