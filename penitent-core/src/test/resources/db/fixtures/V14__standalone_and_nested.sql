--
-- Routines outside a package, collections of collections, and cursors with composite columns.
--

CREATE PROCEDURE FIXTURE_STANDALONE_PROCEDURE(p_value NUMBER, p_result OUT NUMBER) IS
BEGIN
	p_result := p_value * 2;
END;
/

CREATE PROCEDURE FIXTURE_STANDALONE_NOOP IS
BEGIN
	NULL;
END;
/

CREATE FUNCTION FIXTURE_STANDALONE_CONCAT(p_first VARCHAR2, p_second VARCHAR2 DEFAULT 'z') RETURN VARCHAR2 IS
BEGIN
	RETURN p_first || p_second;
END;
/

CREATE SYNONYM FIXTURE_STANDALONE_SYNONYM FOR FIXTURE_STANDALONE_FUNCTION;

CREATE TYPE CUBE_T AS TABLE OF MATRIX_T;
/

CREATE TYPE GRID_T AS OBJECT
(
	CELLS  MATRIX_T
);
/

CREATE OR REPLACE PACKAGE FIXTURE_NESTED AS

	TYPE names IS TABLE OF VARCHAR2(60);
	TYPE matrix IS TABLE OF names;

	FUNCTION echo_cube(p_value CUBE_T) RETURN CUBE_T;
	FUNCTION echo_matrix_pkg(p_value matrix) RETURN matrix;
	FUNCTION echo_grid(p_value GRID_T) RETURN GRID_T;
	FUNCTION null_matrix RETURN MATRIX_T;
	FUNCTION cursor_with_null_object RETURN SYS_REFCURSOR;
	FUNCTION cursor_with_collection RETURN SYS_REFCURSOR;
	FUNCTION numbers_cursor RETURN SYS_REFCURSOR;

END FIXTURE_NESTED;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_NESTED AS

	FUNCTION echo_cube(p_value CUBE_T) RETURN CUBE_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_matrix_pkg(p_value matrix) RETURN matrix IS BEGIN RETURN p_value; END;
	FUNCTION echo_grid(p_value GRID_T) RETURN GRID_T IS BEGIN RETURN p_value; END;
	FUNCTION null_matrix RETURN MATRIX_T IS BEGIN RETURN NULL; END;

	FUNCTION cursor_with_null_object RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR SELECT 2 ID, CAST(NULL AS ADDRESS_T) ADDRESS FROM DUAL;
		RETURN l_cursor;
	END;

	FUNCTION cursor_with_collection RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR SELECT 1 ID, NAME_LIST_T('a') NICKNAMES FROM DUAL;
		RETURN l_cursor;
	END;

	FUNCTION numbers_cursor RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR SELECT LEVEL * 1.5 VALUE FROM DUAL CONNECT BY LEVEL <= 2;
		RETURN l_cursor;
	END;

END FIXTURE_NESTED;
/
