CREATE OR REPLACE PACKAGE FIXTURE_INDEX_BY AS
	TYPE NUMBERS IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
	TYPE BINARIES IS TABLE OF VARCHAR2(10) INDEX BY BINARY_INTEGER;
	TYPE TIME_ZONES IS TABLE OF TIMESTAMP WITH TIME ZONE INDEX BY PLS_INTEGER;
	TYPE ADDRESSES IS TABLE OF ADDRESS_T INDEX BY PLS_INTEGER;
	TYPE BY_TEXT IS TABLE OF VARCHAR2(10) INDEX BY VARCHAR2(10);
	TYPE WITH_NUMBERS IS RECORD (V NUMBERS);
	TYPE WITH_TEXT IS RECORD (V BY_TEXT);

	FUNCTION echo_numbers(p_value NUMBERS) RETURN NUMBERS;
	FUNCTION echo_binaries(p_value BINARIES) RETURN BINARIES;
	FUNCTION echo_time_zones(p_value TIME_ZONES) RETURN TIME_ZONES;
	FUNCTION echo_addresses(p_value ADDRESSES) RETURN ADDRESSES;
	FUNCTION sparse RETURN NUMBERS;
	FUNCTION weighted_sum(p_value NUMBERS) RETURN NUMBER;
	PROCEDURE out_numbers(p_value OUT NUMBERS);
	PROCEDURE change_numbers(p_value IN OUT NUMBERS);
	FUNCTION echo_record(p_value WITH_NUMBERS) RETURN WITH_NUMBERS;
	FUNCTION echo_text_record(p_value WITH_TEXT) RETURN WITH_TEXT;
	FUNCTION text_keys RETURN BY_TEXT;
	FUNCTION read_time_zones RETURN TIME_ZONES;
	FUNCTION read_addresses RETURN ADDRESSES;
	FUNCTION a_record RETURN WITH_NUMBERS;
END FIXTURE_INDEX_BY;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_INDEX_BY AS
	FUNCTION echo_numbers(p_value NUMBERS) RETURN NUMBERS IS BEGIN RETURN p_value; END;
	FUNCTION echo_binaries(p_value BINARIES) RETURN BINARIES IS BEGIN RETURN p_value; END;
	FUNCTION echo_time_zones(p_value TIME_ZONES) RETURN TIME_ZONES IS BEGIN RETURN p_value; END;
	FUNCTION echo_addresses(p_value ADDRESSES) RETURN ADDRESSES IS BEGIN RETURN p_value; END;
	FUNCTION sparse RETURN NUMBERS IS
		l NUMBERS;
	BEGIN
		l(9) := 90;
		l(5) := 50;
		l(-1) := 10;
		RETURN l;
	END;
	FUNCTION weighted_sum(p_value NUMBERS) RETURN NUMBER IS
		l_total NUMBER := 0;
		l_i PLS_INTEGER := p_value.FIRST;
	BEGIN
		WHILE l_i IS NOT NULL LOOP
			l_total := l_total + l_i * p_value(l_i);
			l_i := p_value.NEXT(l_i);
		END LOOP;
		RETURN l_total;
	END;
	PROCEDURE out_numbers(p_value OUT NUMBERS) IS BEGIN p_value(1) := 7; END;
	PROCEDURE change_numbers(p_value IN OUT NUMBERS) IS BEGIN p_value(p_value.COUNT + 1) := 99; END;
	FUNCTION echo_record(p_value WITH_NUMBERS) RETURN WITH_NUMBERS IS BEGIN RETURN p_value; END;
	FUNCTION echo_text_record(p_value WITH_TEXT) RETURN WITH_TEXT IS BEGIN RETURN p_value; END;
	FUNCTION read_time_zones RETURN TIME_ZONES IS
		l TIME_ZONES;
	BEGIN
		l(1) := TO_TIMESTAMP_TZ('2018-01-15 10:30:00 -03:00', 'YYYY-MM-DD HH24:MI:SS TZH:TZM');
		RETURN l;
	END;
	FUNCTION read_addresses RETURN ADDRESSES IS
		l ADDRESSES;
	BEGIN
		l(1) := ADDRESS_T('Street A', 1);
		RETURN l;
	END;
	FUNCTION a_record RETURN WITH_NUMBERS IS
		l WITH_NUMBERS;
	BEGIN
		l.V(1) := 7;
		RETURN l;
	END;
	FUNCTION text_keys RETURN BY_TEXT IS
		l BY_TEXT;
	BEGIN
		l('k') := 'v';
		RETURN l;
	END;
END FIXTURE_INDEX_BY;
