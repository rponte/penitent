	FUNCTION customer_with_active(p_active VARCHAR2) RETURN CUSTOMER_T IS
	BEGIN
		RETURN CUSTOMER_T(1, NULL, p_active, NULL, NULL, NULL, NULL, NULL, NULL);
	END;
END FIXTURE_LITERALS;
