--
-- Boolean properties of a JavaBean read through isX(): ACTIVE is a VARCHAR2(1), Y and N by default, and VIP a
-- NUMBER(1), 1 and 0.
--
CREATE TYPE BEAN_FLAGS_T AS OBJECT (
	ACTIVE VARCHAR2(1),
	VIP    NUMBER(1)
);
/

CREATE TYPE BEAN_ACTIVE_T AS OBJECT (
	ACTIVE VARCHAR2(1)
);
/

CREATE OR REPLACE PACKAGE FIXTURE_BEAN_FLAGS AS
	FUNCTION echo_flags(p_value BEAN_FLAGS_T) RETURN BEAN_FLAGS_T;
	FUNCTION flags_active(p_value BEAN_FLAGS_T) RETURN VARCHAR2;
	FUNCTION active_of(p_value BEAN_ACTIVE_T) RETURN VARCHAR2;
	FUNCTION active_with(p_active VARCHAR2) RETURN BEAN_ACTIVE_T;
END FIXTURE_BEAN_FLAGS;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_BEAN_FLAGS AS
	FUNCTION echo_flags(p_value BEAN_FLAGS_T) RETURN BEAN_FLAGS_T IS BEGIN RETURN p_value; END;
	FUNCTION flags_active(p_value BEAN_FLAGS_T) RETURN VARCHAR2 IS BEGIN RETURN p_value.active; END;
	FUNCTION active_of(p_value BEAN_ACTIVE_T) RETURN VARCHAR2 IS BEGIN RETURN p_value.active; END;
	FUNCTION active_with(p_active VARCHAR2) RETURN BEAN_ACTIVE_T IS BEGIN RETURN BEAN_ACTIVE_T(p_active); END;
END FIXTURE_BEAN_FLAGS;
/
