CREATE TYPE CONV_TEXTS_T AS TABLE OF VARCHAR2(20);
/
CREATE TYPE CONV_DATA_T AS OBJECT (DOCUMENT VARCHAR2(20), CONSENT VARCHAR2(1), NAMES CONV_TEXTS_T);
/
CREATE TYPE CONV_NUMBER_T AS OBJECT (V NUMBER);
/
CREATE TYPE CONV_OBJECTS_T AS TABLE OF CONV_NUMBER_T;
/
CREATE TYPE CONV_ENVELOPE_T AS OBJECT (N CONV_NUMBER_T);
/

CREATE OR REPLACE PACKAGE FIXTURE_CONVERTERS AS
	FUNCTION echo_text(p_value VARCHAR2) RETURN VARCHAR2;
	FUNCTION describe(p_value VARCHAR2) RETURN VARCHAR2;
	FUNCTION null_value RETURN VARCHAR2;
	FUNCTION invalid RETURN VARCHAR2;
	FUNCTION overload(p_value VARCHAR2) RETURN VARCHAR2;
	FUNCTION overload(p_value NUMBER) RETURN VARCHAR2;
	PROCEDURE out_text(p_value OUT VARCHAR2);
	PROCEDURE change_text(p_value IN OUT VARCHAR2);
	FUNCTION echo_timestamp(p_value TIMESTAMP) RETURN TIMESTAMP;
	FUNCTION echo_texts(p_value CONV_TEXTS_T) RETURN CONV_TEXTS_T;
	FUNCTION count_texts(p_value CONV_TEXTS_T) RETURN NUMBER;
	FUNCTION echo_data(p_value CONV_DATA_T) RETURN CONV_DATA_T;
	FUNCTION echo_number_obj(p_value CONV_NUMBER_T) RETURN CONV_NUMBER_T;
	FUNCTION echo_objects(p_value CONV_OBJECTS_T) RETURN CONV_OBJECTS_T;
	FUNCTION null_number RETURN CONV_NUMBER_T;
	FUNCTION echo_envelope(p_value CONV_ENVELOPE_T) RETURN CONV_ENVELOPE_T;
	FUNCTION items RETURN SYS_REFCURSOR;
END FIXTURE_CONVERTERS;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_CONVERTERS AS
	FUNCTION echo_text(p_value VARCHAR2) RETURN VARCHAR2 IS BEGIN RETURN p_value; END;
	FUNCTION describe(p_value VARCHAR2) RETURN VARCHAR2 IS
	BEGIN RETURN CASE WHEN p_value IS NULL THEN 'got NULL' ELSE 'got ' || p_value END; END;
	FUNCTION null_value RETURN VARCHAR2 IS BEGIN RETURN NULL; END;
	FUNCTION invalid RETURN VARCHAR2 IS BEGIN RETURN 'X'; END;
	FUNCTION overload(p_value VARCHAR2) RETURN VARCHAR2 IS BEGIN RETURN 'text'; END;
	FUNCTION overload(p_value NUMBER) RETURN VARCHAR2 IS BEGIN RETURN 'number'; END;
	PROCEDURE out_text(p_value OUT VARCHAR2) IS BEGIN p_value := '123'; END;
	PROCEDURE change_text(p_value IN OUT VARCHAR2) IS BEGIN p_value := p_value || '9'; END;
	FUNCTION echo_timestamp(p_value TIMESTAMP) RETURN TIMESTAMP IS BEGIN RETURN p_value; END;
	FUNCTION echo_texts(p_value CONV_TEXTS_T) RETURN CONV_TEXTS_T IS BEGIN RETURN p_value; END;
	FUNCTION count_texts(p_value CONV_TEXTS_T) RETURN NUMBER IS
	BEGIN RETURN CASE WHEN p_value IS NULL THEN -1 ELSE p_value.COUNT END; END;
	FUNCTION echo_data(p_value CONV_DATA_T) RETURN CONV_DATA_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_number_obj(p_value CONV_NUMBER_T) RETURN CONV_NUMBER_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_objects(p_value CONV_OBJECTS_T) RETURN CONV_OBJECTS_T IS BEGIN RETURN p_value; END;
	FUNCTION null_number RETURN CONV_NUMBER_T IS BEGIN RETURN CONV_NUMBER_T(NULL); END;
	FUNCTION echo_envelope(p_value CONV_ENVELOPE_T) RETURN CONV_ENVELOPE_T IS BEGIN RETURN p_value; END;
	FUNCTION items RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR
			SELECT '123' AS DOCUMENT, 'Y' AS CONSENT, CAST(NULL AS NUMBER) AS QUANTITY FROM DUAL
			UNION ALL
			SELECT NULL, NULL, 1 FROM DUAL;
		RETURN l_cursor;
	END;
END FIXTURE_CONVERTERS;
