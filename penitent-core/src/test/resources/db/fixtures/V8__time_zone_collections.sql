CREATE TYPE TSTZ_LIST_T AS TABLE OF TIMESTAMP WITH TIME ZONE;
/
CREATE TYPE TSTZ_VARRAY_T AS VARRAY(5) OF TIMESTAMP WITH TIME ZONE;
/
CREATE TYPE TSLTZ_LIST_T AS TABLE OF TIMESTAMP WITH LOCAL TIME ZONE;
/
CREATE TYPE TIMESTAMP_LIST_T AS TABLE OF TIMESTAMP;
/
CREATE TYPE ATTR_TSTZ_LIST_T AS OBJECT (V TSTZ_LIST_T);
/

CREATE OR REPLACE PACKAGE FIXTURE_TIME_ZONE_LISTS AS
	TYPE TSTZ_PKG_LIST IS TABLE OF TIMESTAMP WITH TIME ZONE;

	FUNCTION echo_tstz(p_value TSTZ_LIST_T) RETURN TSTZ_LIST_T;
	FUNCTION echo_varray(p_value TSTZ_VARRAY_T) RETURN TSTZ_VARRAY_T;
	FUNCTION echo_pkg(p_value TSTZ_PKG_LIST) RETURN TSTZ_PKG_LIST;
	FUNCTION echo_tsltz(p_value TSLTZ_LIST_T) RETURN TSLTZ_LIST_T;
	FUNCTION echo_timestamp(p_value TIMESTAMP_LIST_T) RETURN TIMESTAMP_LIST_T;
	FUNCTION in_tokyo RETURN TSTZ_LIST_T;
	PROCEDURE out_tstz(p_value OUT TSTZ_LIST_T);
	FUNCTION echo_attribute(p_value ATTR_TSTZ_LIST_T) RETURN ATTR_TSTZ_LIST_T;
END FIXTURE_TIME_ZONE_LISTS;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_TIME_ZONE_LISTS AS
	c_tokyo CONSTANT TIMESTAMP WITH TIME ZONE
		:= TO_TIMESTAMP_TZ('2018-01-15 10:30:00 Asia/Tokyo', 'YYYY-MM-DD HH24:MI:SS TZR');

	FUNCTION echo_tstz(p_value TSTZ_LIST_T) RETURN TSTZ_LIST_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_varray(p_value TSTZ_VARRAY_T) RETURN TSTZ_VARRAY_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_pkg(p_value TSTZ_PKG_LIST) RETURN TSTZ_PKG_LIST IS BEGIN RETURN p_value; END;
	FUNCTION echo_tsltz(p_value TSLTZ_LIST_T) RETURN TSLTZ_LIST_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_timestamp(p_value TIMESTAMP_LIST_T) RETURN TIMESTAMP_LIST_T IS BEGIN RETURN p_value; END;
	FUNCTION in_tokyo RETURN TSTZ_LIST_T IS BEGIN RETURN TSTZ_LIST_T(c_tokyo); END;
	PROCEDURE out_tstz(p_value OUT TSTZ_LIST_T) IS BEGIN p_value := TSTZ_LIST_T(c_tokyo); END;
	FUNCTION echo_attribute(p_value ATTR_TSTZ_LIST_T) RETURN ATTR_TSTZ_LIST_T IS BEGIN RETURN p_value; END;
END FIXTURE_TIME_ZONE_LISTS;
/

