CREATE TYPE ATTR_TSLTZ_T AS OBJECT (V TIMESTAMP WITH LOCAL TIME ZONE);
/

CREATE OR REPLACE PACKAGE FIXTURE_TIME_ZONE AS
	FUNCTION echo_tstz(p_value TIMESTAMP WITH TIME ZONE) RETURN TIMESTAMP WITH TIME ZONE;
	FUNCTION echo_tsltz(p_value TIMESTAMP WITH LOCAL TIME ZONE) RETURN TIMESTAMP WITH LOCAL TIME ZONE;
	FUNCTION echo_timestamp(p_value TIMESTAMP) RETURN TIMESTAMP;
	FUNCTION echo_date(p_value DATE) RETURN DATE;
	FUNCTION in_tokyo RETURN TIMESTAMP WITH TIME ZONE;
	FUNCTION as_stored(p_value TIMESTAMP WITH TIME ZONE) RETURN VARCHAR2;
	PROCEDURE out_tstz(p_value OUT TIMESTAMP WITH TIME ZONE);
	PROCEDURE change_tstz(p_value IN OUT TIMESTAMP WITH TIME ZONE);
	PROCEDURE out_tsltz(p_value OUT TIMESTAMP WITH LOCAL TIME ZONE);
	FUNCTION echo_attribute_tstz(p_value ATTR_TSTZ_T) RETURN ATTR_TSTZ_T;
	FUNCTION echo_attribute_tsltz(p_value ATTR_TSLTZ_T) RETURN ATTR_TSLTZ_T;
	FUNCTION attribute_in_tokyo RETURN ATTR_TSTZ_T;
	FUNCTION dates_cursor RETURN SYS_REFCURSOR;
	FUNCTION overload(p_value TIMESTAMP) RETURN VARCHAR2;
	FUNCTION overload(p_value TIMESTAMP WITH TIME ZONE) RETURN VARCHAR2;
END FIXTURE_TIME_ZONE;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_TIME_ZONE AS
	c_tokyo CONSTANT TIMESTAMP WITH TIME ZONE
		:= TO_TIMESTAMP_TZ('2018-01-15 10:30:00 Asia/Tokyo', 'YYYY-MM-DD HH24:MI:SS TZR');

	FUNCTION echo_tstz(p_value TIMESTAMP WITH TIME ZONE) RETURN TIMESTAMP WITH TIME ZONE IS BEGIN RETURN p_value; END;
	FUNCTION echo_tsltz(p_value TIMESTAMP WITH LOCAL TIME ZONE) RETURN TIMESTAMP WITH LOCAL TIME ZONE IS BEGIN RETURN p_value; END;
	FUNCTION echo_timestamp(p_value TIMESTAMP) RETURN TIMESTAMP IS BEGIN RETURN p_value; END;
	FUNCTION echo_date(p_value DATE) RETURN DATE IS BEGIN RETURN p_value; END;
	FUNCTION in_tokyo RETURN TIMESTAMP WITH TIME ZONE IS BEGIN RETURN c_tokyo; END;
	FUNCTION as_stored(p_value TIMESTAMP WITH TIME ZONE) RETURN VARCHAR2 IS
	BEGIN RETURN TO_CHAR(p_value, 'HH24:MI TZH:TZM'); END;
	PROCEDURE out_tstz(p_value OUT TIMESTAMP WITH TIME ZONE) IS BEGIN p_value := c_tokyo; END;
	PROCEDURE change_tstz(p_value IN OUT TIMESTAMP WITH TIME ZONE) IS BEGIN p_value := p_value + INTERVAL '1' HOUR; END;
	PROCEDURE out_tsltz(p_value OUT TIMESTAMP WITH LOCAL TIME ZONE) IS BEGIN p_value := c_tokyo; END;
	FUNCTION echo_attribute_tstz(p_value ATTR_TSTZ_T) RETURN ATTR_TSTZ_T IS BEGIN RETURN p_value; END;
	FUNCTION echo_attribute_tsltz(p_value ATTR_TSLTZ_T) RETURN ATTR_TSLTZ_T IS BEGIN RETURN p_value; END;
	FUNCTION attribute_in_tokyo RETURN ATTR_TSTZ_T IS BEGIN RETURN ATTR_TSTZ_T(c_tokyo); END;
	FUNCTION dates_cursor RETURN SYS_REFCURSOR IS
		l_cursor SYS_REFCURSOR;
	BEGIN
		OPEN l_cursor FOR
			SELECT c_tokyo AS WITH_TIME_ZONE,
				CAST(c_tokyo AS TIMESTAMP WITH LOCAL TIME ZONE) AS SESSION_LOCAL,
				CAST(c_tokyo AS TIMESTAMP) AS WITHOUT_TIME_ZONE
			FROM DUAL;
		RETURN l_cursor;
	END;
	FUNCTION overload(p_value TIMESTAMP) RETURN VARCHAR2 IS BEGIN RETURN 'without time zone'; END;
	FUNCTION overload(p_value TIMESTAMP WITH TIME ZONE) RETURN VARCHAR2 IS BEGIN RETURN 'with time zone'; END;
END FIXTURE_TIME_ZONE;
