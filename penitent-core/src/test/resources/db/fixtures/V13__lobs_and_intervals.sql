-- LOBs above 32 KB in both directions, and the intervals.
CREATE OR REPLACE PACKAGE FIXTURE_LOBS AS
	FUNCTION clob_length(p_value CLOB) RETURN NUMBER;
	FUNCTION blob_length(p_value BLOB) RETURN NUMBER;
	PROCEDURE large_clob(p_size NUMBER, p_value OUT CLOB);
	FUNCTION echo_interval_ym(p_value INTERVAL YEAR TO MONTH) RETURN INTERVAL YEAR TO MONTH;
END FIXTURE_LOBS;
/

CREATE OR REPLACE PACKAGE BODY FIXTURE_LOBS AS
	FUNCTION clob_length(p_value CLOB) RETURN NUMBER IS BEGIN RETURN DBMS_LOB.GETLENGTH(p_value); END;

	FUNCTION blob_length(p_value BLOB) RETURN NUMBER IS BEGIN RETURN DBMS_LOB.GETLENGTH(p_value); END;

	PROCEDURE large_clob(p_size NUMBER, p_value OUT CLOB) IS
		v_chunk VARCHAR2(1000) := RPAD('y', 1000, 'y');
	BEGIN
		DBMS_LOB.CREATETEMPORARY(p_value, TRUE);
		FOR i IN 1 .. p_size / 1000 LOOP
			DBMS_LOB.WRITEAPPEND(p_value, 1000, v_chunk);
		END LOOP;
	END;

	FUNCTION echo_interval_ym(p_value INTERVAL YEAR TO MONTH) RETURN INTERVAL YEAR TO MONTH IS
	BEGIN
		RETURN p_value;
	END;
END FIXTURE_LOBS;
/
